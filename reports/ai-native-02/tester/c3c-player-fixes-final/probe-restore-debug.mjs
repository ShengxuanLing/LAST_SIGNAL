import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { randomBytes } from 'node:crypto';
const SNAP='D:/Project/AI-NATIVE-02-snapshots/8f1ce6c';
const c=new Client({name:'dbg',version:'1.0.0'});
await c.connect(new StdioClientTransport({command:'node',args:[SNAP+'/dist-mcp/worldHeadlessMcpServer.mjs','--dev'],cwd:SNAP,env:{...process.env},stderr:'pipe'}));
const call=async(n,a)=>{const r=await c.callTool({name:n,arguments:a});const t=r.content?.[0]?.text??'';let b;try{b=JSON.parse(t)}catch{b={raw:t}};return {isError:!!r.isError,body:b}};
const req=()=>'req_'+randomBytes(12).toString('hex');
const aid=()=>'aid_'+randomBytes(12).toString('hex');
const cr=await call('world_headless_create_session',{seed:777});
const s=cr.body;
const snap=await call('world_headless_dev_snapshot',{session:s.session});
console.log('snap',snap.body.ok,snap.body.frameBytes);
await call('world_action',{session:s.session,epoch:s.epoch,requestId:req(),actions:[{type:'move',actionId:aid(),dir:{x:1,y:0},ticks:120}]});
const st=await call('world_headless_step',{session:s.session,epoch:s.epoch,requestId:req(),ticks:10});
console.log('step10',st.body.ok,st.body.executing,st.body.code);
const rs=await call('world_headless_dev_restore',{session:s.session,frame:snap.body.frame});
console.log('restore',JSON.stringify({ok:rs.body.ok,code:rs.body.code,epoch:rs.body.epoch,status:rs.body.status}).slice(0,400));
const stale=await call('world_headless_step',{session:s.session,epoch:s.epoch,requestId:req(),ticks:5});
console.log('stale',JSON.stringify(stale.body).slice(0,250));
const af=await call('world_headless_step',{session:s.session,epoch:rs.body.epoch,requestId:req(),ticks:20});
console.log('after',JSON.stringify({ok:af.body.ok,code:af.body.code,applied:af.body.applied,exec:af.body.executing,toTick:af.body.toTick}).slice(0,400));
const ob=await call('world_observe',{session:s.session});
console.log('observe',JSON.stringify({ok:ob.body.ok,code:ob.body.code,hasObs:!!ob.body.observation,tick:ob.body.observation?.tick}).slice(0,300));
await c.close();
