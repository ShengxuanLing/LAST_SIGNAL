import { chromium } from 'playwright';
const b=await chromium.launch({args:['--no-sandbox']});
const page=await b.newPage({viewport:{width:1280,height:720}});
await page.goto('http://localhost:5361/',{waitUntil:'load'});
await page.waitForFunction(()=>window.__game?.scene.isActive('MainMenuScene'));
await page.mouse.click(640,340);
await page.waitForFunction(()=>window.__game?.scene.isActive('GameScene'));
await page.waitForTimeout(500);
const clickText=async(prefix)=>{const pos=await page.evaluate((p)=>{const s=window.__game.scene.getScene('PauseScene');const t=s?.children.list.find(c=>c.type==='Text'&&(c.text||'').startsWith(p));return t?{x:t.x+(t.width||0)/2,y:t.y+(t.height||0)/2,ox:t.x,oy:t.y,origin:t.originX}:null;},prefix);if(!pos)return null;await page.mouse.click(Math.round(pos.x),Math.round(pos.y));return pos;};
const armed=()=>page.evaluate(()=>window.__game.scene.getScene('GameScene').world.echoAssistArmed);
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
console.log('echo link',await clickText('ECHO COMPANION'));
await page.waitForTimeout(400);
console.log('enable',await clickText('ENABLE ECHO'));
await page.waitForTimeout(300);
await page.keyboard.press('Escape'); await page.waitForTimeout(600);
console.log('armed initial',await armed());
// spawn drone near echo so suggestion fire
const sp=await page.evaluate(()=>{const gs=window.__game.scene.getScene('GameScene');const w=gs.world;const e=w.echoActor;const room=w.currentRoom();w.spawnEnemy('drone',e.x+2,e.y,room?.id??0,1);return {x:e.x,y:e.y};});
await page.waitForTimeout(600);
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
console.log('open',await clickText('ECHO COMPANION'));
await page.waitForTimeout(300);
console.log('confirm',await clickText('CONFIRM ASSIST FIRE'));
await page.waitForTimeout(400);
console.log('armed after confirm (paused)',await armed());
await page.keyboard.press('Escape'); await page.waitForTimeout(500);
console.log('armed after resume',await armed());
await page.keyboard.press('Escape'); await page.waitForTimeout(400);
await clickText('ECHO COMPANION'); await page.waitForTimeout(300);
const pos=await page.evaluate(()=>{const s=window.__game.scene.getScene('PauseScene');const ts=s.children.list.filter(c=>c.type==='Text').map(c=>({t:c.text,x:c.x,y:c.y,w:c.width,h:c.height,ox:c.originX,oy:c.originY}));return ts.filter(x=>/ASSIST|CONFIRM|REVOKE|ECHO/.test(x.t));});
console.log('texts',JSON.stringify(pos,null,1));
const click=await clickText('ASSIST ARMED — CLICK TO REVOKE');
console.log('revoke click',click);
console.log('armed immediately after click',await armed());
await page.waitForTimeout(400);
console.log('armed 400ms later',await armed());
await page.screenshot({path:'D:/Project/LAST_SIGNAL/reports/ai-native-02/tester/p3a-final/evidence/debug-revoke.png'});
await b.close();
